/** 1-12, shared by Sales Target's form/filter and the Dashboard's Pencapaian Sales period selector. */
export const MONTH_OPTIONS: { value: number; label: string }[] = [
  { value: 1, label: 'January' },
  { value: 2, label: 'February' },
  { value: 3, label: 'March' },
  { value: 4, label: 'April' },
  { value: 5, label: 'May' },
  { value: 6, label: 'June' },
  { value: 7, label: 'July' },
  { value: 8, label: 'August' },
  { value: 9, label: 'September' },
  { value: 10, label: 'October' },
  { value: 11, label: 'November' },
  { value: 12, label: 'December' },
]

export function monthLabel(month: number): string {
  return MONTH_OPTIONS.find((option) => option.value === month)?.label ?? String(month)
}
